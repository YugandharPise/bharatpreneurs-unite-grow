const OfferingsSection = () => {
  const sectionRef = useRef<HTMLDivElement>(null);
  const itemRefs = useRef<Array<HTMLDivElement | null>>([]);

  useEffect(() => {
    const observer = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          if (entry.isIntersecting) {
            entry.target.classList.add('animated');
            observer.unobserve(entry.target);
          }
        });
      },
      {
        root: null,
        threshold: 0.1,
      }
    );

    if (sectionRef.current) {
      observer.observe(sectionRef.current);
    }

    itemRefs.current.forEach((ref) => {
      if (ref) observer.observe(ref);
    });

    return () => {
      if (sectionRef.current) {
        observer.unobserve(sectionRef.current);
      }
      itemRefs.current.forEach((ref) => {
        if (ref) observer.unobserve(ref);
      });
    };
  }, []);

  return (
    <section id="offerings" className="section-padding bg-white">
      <div 
        ref={sectionRef}
        className="container mx-auto animate-on-scroll"
      >
        <div className="text-center mb-12">
          <h2 className="text-3xl md:text-4xl font-bold mb-4">Our Offerings</h2>
          <div className="h-1 w-20 bg-gold mx-auto mb-6"></div>
          <p className="text-gray-700 max-w-2xl mx-auto">
            At Bharatpreneurs, we provide a comprehensive suite of services designed to accelerate your entrepreneurial journey.
          </p>
        </div>

        <div className="grid md:grid-cols-2 lg:grid-cols-4 gap-8">
          {offerings.map((offering, index) => (
            <div
              key={offering.id}
              ref={(el) => (itemRefs.current[index] = el)}
              className="service-card animate-on-scroll"
              style={{ transitionDelay: `${index * 100}ms` }}
            >
              <div className="mb-4">{offering.icon}</div>
              <h3 className="text-xl font-bold mb-3">{offering.title}</h3>
              <p className="text-gray-600">{offering.description}</p>
            </div>
          ))}
        </div>
      </div>
    </section>
  );
};

export default OfferingsSection;
